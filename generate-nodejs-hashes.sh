#!/usr/bin/env bash
# Regenerate nodejs-hashes.nix: SHA256 hashes of the official prebuilt Node.js
# tarballs from nodejs.org, for every stable release of each major line.
#
# imports/make-nodejs.nix uses these when the app asks for a Node.js major
# that the nixpkgs in use doesn't package (anything EOL, e.g. 14/16/18).
#
# The hashes are nodejs.org's own published SHASUMS256.txt values, so the
# whole file is regenerated from scratch each run (no per-platform builds).
#
# Usage: ./generate-nodejs-hashes.sh            # all majors >= 10
#        ./generate-nodejs-hashes.sh 14 16 18   # only these majors
#
# Requires: curl, jq.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="$SCRIPT_DIR/nodejs-hashes.nix"
DIST="https://nodejs.org/dist"
MIN_MAJOR=10

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "Querying $DIST/index.json..."
curl -fsSL "$DIST/index.json" -o "$WORK/index.json"

if [ $# -gt 0 ]; then
  majors_filter=$(printf '%s\n' "$@" | jq -R 'tonumber' | jq -sc .)
else
  majors_filter="null"
fi

jq -r --argjson min "$MIN_MAJOR" --argjson only "$majors_filter" '
  .[].version | ltrimstr("v")
  | select((split(".")[0] | tonumber) as $m
           | $m >= $min and ($only == null or ($only | index($m)) != null))
' "$WORK/index.json" | sort -V > "$WORK/versions"

total=$(wc -l < "$WORK/versions")
echo "Fetching SHASUMS256.txt for $total versions..."

mkdir -p "$WORK/sums"
export DIST WORK
xargs -P 16 -I{} sh -c \
  'curl -fsSL --retry 3 "$DIST/v{}/SHASUMS256.txt" -o "$WORK/sums/{}" || echo "  WARN: no SHASUMS256.txt for {}" >&2' \
  < "$WORK/versions"

# nix system -> tarball suffix. Linux uses .tar.xz; darwin uses .tar.gz
# (older darwin releases have no .tar.xz).
platforms=(
  "x86_64-linux:linux-x64.tar.xz"
  "aarch64-linux:linux-arm64.tar.xz"
  "x86_64-darwin:darwin-x64.tar.gz"
  "aarch64-darwin:darwin-arm64.tar.gz"
)

{
  echo "# SHA256 hashes of the official prebuilt Node.js tarballs (nodejs.org/dist)."
  echo "# Format: version.\${system} = \"hex sha256\" (from each release's SHASUMS256.txt)"
  echo "#"
  echo "# GENERATED by ./generate-nodejs-hashes.sh — do not edit by hand."
  echo "# Used by imports/make-nodejs.nix for Node.js majors nixpkgs doesn't package."
  echo "{"
  while IFS= read -r v; do
    sums="$WORK/sums/$v"
    [ -f "$sums" ] || continue
    entries=""
    for p in "${platforms[@]}"; do
      sys="${p%%:*}"
      file="node-v$v-${p#*:}"
      hash=$(awk -v f="$file" '$2 == f { print $1 }' "$sums")
      [ -n "$hash" ] && entries+="    \"$sys\" = \"$hash\";"$'\n'
    done
    [ -n "$entries" ] || continue
    echo "  \"$v\" = {"
    printf '%s' "$entries"
    echo "  };"
  done < "$WORK/versions"
  echo "}"
} > "$OUTPUT_FILE.tmp"

mv "$OUTPUT_FILE.tmp" "$OUTPUT_FILE"
echo "Wrote $OUTPUT_FILE ($(grep -c '^  "' "$OUTPUT_FILE") versions)"
